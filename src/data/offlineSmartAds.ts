// Shuffle helper for true rotation every time
export function getRandomSmartAds(count: number = 6): OfflineAdItem[] {
  const shuffled = [...OFFLINE_SMART_ADS].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

// Offline click sync queue
export function recordSmartAdClick(ad: OfflineAdItem) {
  try {
    const history = JSON.parse(localStorage.getItem('toolbazar_ad_clicks') || '[]');
    history.push({
      adId: ad.id,
      title: ad.title,
      timestamp: Date.now(),
      online: navigator.onLine,
    });
    localStorage.setItem('toolbazar_ad_clicks', JSON.stringify(history.slice(-50)));
  } catch (e) {
    // Ignore storage issues
  }

  // Open direct sponsor url (works online, queues when offline)
  if (ad.directUrl) {
    window.open(ad.directUrl, '_blank', 'noopener,noreferrer');
  }
}
